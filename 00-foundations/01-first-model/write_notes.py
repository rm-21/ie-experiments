"""Step 4: build notes/week-01.md from the CSV and tokens.json.

The data sections are regenerated every time. Everything from the
"## My observation" heading down is yours and is kept on re-runs.
"""

import csv
import json
from pathlib import Path

from foundations import MODEL, resolved_revision

# Outputs live next to this script, whatever directory you run it from.
LESSON_DIR = Path(__file__).resolve().parent
BENCH_DIR = LESSON_DIR / "benchmarks"
NOTES_DIR = LESSON_DIR / "notes"


MARKER = "## My observation"
YOUR_SECTION = f"""{MARKER}

TODO: one thing you noticed in the numbers above.

## Questions to revisit after Phase 3 (don't answer yet)

1. Which part took longer with more input?
2. What might change if two users shared the model?
"""


def main() -> None:
    rows = list(csv.DictReader((BENCH_DIR / "week-01-baseline.csv").open()))
    tokens = json.loads((BENCH_DIR / "tokens.json").read_text())

    lines = [
        "# Week 01: first local model baseline",
        "",
        "_Data sections generated by `01-first-model/write_notes.py`._",
        "",
        f"- model: `{MODEL}`",
        f"- revision: `{resolved_revision()}`",
        f"- command: `{rows[0]['command']}` (prompt varies, see `benchmarks/prompts/`)",
        "",
        "## Baseline (second run of each prompt)",
        "",
        "| prompt | prompt tokens | prompt tok/s | gen tokens | gen tok/s | peak GB | process wall s* |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['prompt_name']} | {r['prompt_tokens']} | {r['prompt_tps']} | {r['generation_tokens']} "
            f"| {r['generation_tps']} | {r['peak_memory_gb']} | {r['process_wall_s']} |"
        )
    lines += [
        "",
        "\\* Launch to exit, includes startup and model load. Not TTFT.",
        "",
        "## Plain-text tokenization (no chat template)",
        "",
        "| variant | text | words | UTF-8 bytes | tokens | pieces |",
        "|---|---|---|---|---|---|",
    ]
    for t in tokens:
        pieces = " · ".join(f"`{p}`" for p in t["pieces"])
        lines.append(
            f"| {t['label']} | `{t['text']}` | {t['word_count']} | {t['utf8_bytes']} | {t['token_count']} | {pieces} |"
        )
    lines += [
        "",
        (
            f"The CLI reported {rows[0]['prompt_tokens']} prompt tokens for the short prompt vs "
            f"{tokens[0]['token_count']} here: the difference is the chat template's role/control tokens."
        ),
        "",
    ]

    out = NOTES_DIR / "week-01.md"
    # Keep whatever you've written below the marker.
    existing = out.read_text() if out.exists() else ""
    mine = existing[existing.index(MARKER) :] if MARKER in existing else YOUR_SECTION

    NOTES_DIR.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n" + mine)
    print(f"saved: {out.relative_to(LESSON_DIR)}")


if __name__ == "__main__":
    main()
