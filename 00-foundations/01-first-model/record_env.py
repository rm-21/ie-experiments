"""Step 1: record what this baseline ran on -> ENVIRONMENT.md (generated, don't edit)."""

import platform
import subprocess
import sys
from datetime import datetime
from pathlib import Path

from foundations import MODEL, resolved_revision

# Outputs live next to this script, whatever directory you run it from.
LESSON_DIR = Path(__file__).resolve().parent


def sh(*cmd: str) -> str:
    return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.strip()


def main() -> None:
    mem_gb = int(sh("sysctl", "-n", "hw.memsize")) / 1024**3
    freeze = sh("uv", "pip", "freeze", "--python", sys.executable)

    lines = [
        "# Environment",
        "",
        f"_Generated by `01-first-model/record_env.py` on {datetime.now().astimezone().date()}. Re-run it instead of editing._",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Model | `{MODEL}` |",
        f"| Resolved revision | `{resolved_revision()}` |",
        f"| Mac model | {sh('sysctl', '-n', 'hw.model')} ({sh('sysctl', '-n', 'machdep.cpu.brand_string')}) |",
        f"| Memory | {mem_gb:.0f} GB |",
        f"| macOS | {sh('sw_vers', '-productVersion')} (build {sh('sw_vers', '-buildVersion')}) |",
        f"| Python | {platform.python_version()} |",
        f"| uv | {sh('uv', '--version')} |",
        "",
        f"## Packages (`uv pip freeze --python {Path(sys.executable).relative_to(LESSON_DIR.parents[1], walk_up=True)}`)",
        "",
        "```",
        freeze,
        "```",
        "",
    ]
    out = LESSON_DIR / "ENVIRONMENT.md"
    out.write_text("\n".join(lines))
    print(f"saved: {out.relative_to(LESSON_DIR)}")


if __name__ == "__main__":
    main()
